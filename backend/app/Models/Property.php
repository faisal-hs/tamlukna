<?php

namespace App\Models;

use App\Enums\Facade;
use App\Enums\Furnishing;
use App\Enums\ListingStatus;
use App\Enums\PropertyCondition;
use App\Enums\PropertyPurpose;
use App\Enums\RentPeriod;
use App\Enums\VerificationStatus;
use App\Support\Properties\PropertyReference;
use Database\Factories\PropertyFactory;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;

/**
 * "location" (POINT) and "price_per_sqm" are generated by MySQL; never write them.
 * Do not use replicate(): it would copy the generated columns into an INSERT.
 *
 * @property int $id
 * @property string $reference
 * @property int $advertiser_id
 * @property int $property_type_id
 * @property PropertyPurpose $purpose
 * @property RentPeriod|null $rent_period
 * @property PropertyCondition|null $property_condition
 * @property ListingStatus $status
 * @property VerificationStatus $verification_status
 * @property string $title_ar
 * @property string|null $title_en
 * @property string|null $description_ar
 * @property string|null $description_en
 * @property int $city_id
 * @property int|null $district_id
 * @property string|null $address_line
 * @property string $latitude
 * @property string $longitude
 * @property string $area_sqm
 * @property string|null $street_width_m
 * @property Facade|null $facade
 * @property int|null $bedrooms
 * @property int|null $bathrooms
 * @property int|null $living_rooms
 * @property int|null $floor_number
 * @property int|null $total_floors
 * @property int|null $building_age_years
 * @property Furnishing|null $furnishing
 * @property string $price
 * @property string $currency
 * @property string|null $price_per_sqm
 * @property string|null $ad_license_number
 * @property Carbon|null $submitted_at
 * @property Carbon|null $published_at
 * @property Carbon|null $expires_at
 * @property Carbon|null $moderated_at
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 */
class Property extends Model
{
    /** @use HasFactory<PropertyFactory> */
    use HasFactory, SoftDeletes;

    /**
     * Content the advertiser may edit. Lifecycle fields (reference, advertiser,
     * status, verification, timestamps) are set only by domain services.
     *
     * @var list<string>
     */
    protected $fillable = [
        'property_type_id',
        'purpose',
        'rent_period',
        'property_condition',
        'title_ar',
        'title_en',
        'description_ar',
        'description_en',
        'city_id',
        'district_id',
        'address_line',
        'latitude',
        'longitude',
        'area_sqm',
        'street_width_m',
        'facade',
        'bedrooms',
        'bathrooms',
        'living_rooms',
        'floor_number',
        'total_floors',
        'building_age_years',
        'furnishing',
        'price',
        'ad_license_number',
    ];

    /**
     * @var list<string>
     */
    protected $hidden = [
        'location',
    ];

    /**
     * @var array<string, mixed>
     */
    protected $attributes = [
        'status' => 'draft',
        'verification_status' => 'unverified',
        'currency' => 'SAR',
    ];

    protected static function booted(): void
    {
        static::creating(function (Property $property): void {
            if (($property->getAttributes()['reference'] ?? null) !== null) {
                return;
            }

            do {
                $reference = PropertyReference::generate();
            } while (static::withTrashed()->where('reference', $reference)->exists());

            $property->reference = $reference;
        });
    }

    public function getRouteKeyName(): string
    {
        return 'reference';
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'purpose' => PropertyPurpose::class,
            'rent_period' => RentPeriod::class,
            'property_condition' => PropertyCondition::class,
            'status' => ListingStatus::class,
            'verification_status' => VerificationStatus::class,
            'facade' => Facade::class,
            'furnishing' => Furnishing::class,
            'latitude' => 'decimal:7',
            'longitude' => 'decimal:7',
            'area_sqm' => 'decimal:2',
            'street_width_m' => 'decimal:2',
            'price' => 'decimal:2',
            'price_per_sqm' => 'decimal:2',
            'bedrooms' => 'integer',
            'bathrooms' => 'integer',
            'living_rooms' => 'integer',
            'floor_number' => 'integer',
            'total_floors' => 'integer',
            'building_age_years' => 'integer',
            'submitted_at' => 'datetime',
            'published_at' => 'datetime',
            'expires_at' => 'datetime',
            'moderated_at' => 'datetime',
        ];
    }

    /**
     * Publicly visible listings: published and not past their expiry date.
     *
     * @param  Builder<Property>  $query
     */
    public function scopePublished(Builder $query): void
    {
        $query->where('status', ListingStatus::Published)
            ->where(fn (Builder $q) => $q->whereNull('expires_at')->orWhere('expires_at', '>', now()));
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function advertiser(): BelongsTo
    {
        return $this->belongsTo(User::class, 'advertiser_id');
    }

    /**
     * @return BelongsTo<PropertyType, $this>
     */
    public function propertyType(): BelongsTo
    {
        return $this->belongsTo(PropertyType::class);
    }

    /**
     * @return BelongsTo<City, $this>
     */
    public function city(): BelongsTo
    {
        return $this->belongsTo(City::class);
    }

    /**
     * @return BelongsTo<District, $this>
     */
    public function district(): BelongsTo
    {
        return $this->belongsTo(District::class);
    }

    /**
     * @return BelongsToMany<Feature, $this>
     */
    public function features(): BelongsToMany
    {
        return $this->belongsToMany(Feature::class, 'property_feature');
    }

    /**
     * @return HasMany<PropertyMedia, $this>
     */
    public function media(): HasMany
    {
        return $this->hasMany(PropertyMedia::class)->orderBy('sort_order')->orderBy('id');
    }

    /**
     * @return HasOne<PropertyMedia, $this>
     */
    public function cover(): HasOne
    {
        return $this->hasOne(PropertyMedia::class)->where('is_cover', true);
    }

    /**
     * @return HasMany<PropertyStatusHistory, $this>
     */
    public function statusHistory(): HasMany
    {
        return $this->hasMany(PropertyStatusHistory::class)->orderBy('created_at')->orderBy('id');
    }
}
